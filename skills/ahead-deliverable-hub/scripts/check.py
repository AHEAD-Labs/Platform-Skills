#!/usr/bin/env python3
"""Quality checks for a hub HTML file: structure, self-containment, links, placeholders and house style.

  python3 check.py hub.html [--client "Contoso"] [--final] [--internal-names "A Person,B Person"] [--skip-spelling]

Exit code 1 if there are errors. With --final, any remaining placeholder is an error.
Owners named on slots are treated as delivery-team names and flagged if they appear in the content.
"""
import argparse, collections, html as H, re, sys
from html.parser import HTMLParser
# Make this script's own folder importable even when PYTHONSAFEPATH is set (e.g. the Glean sandbox).
import sys as _sys, pathlib as _pathlib
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parent))
from guide import slots

BANNED = [  # casual, hype or filler phrasing that does not belong in a client deliverable
    'bottom line', 'landed on', 'excited about', 'excited to', 'thrilled', 'game-changer', 'game changer',
    'best-in-class', 'world-class', 'cutting-edge', 'cutting edge', 'synergy', 'synergies', 'seamless', 'seamlessly',
    'robust solution', 'leverage our', 'deep dive into', 'needle-moving', 'low-hanging fruit', 'at the end of the day',
    'circle back', 'move the needle', 'secret sauce', 'no-brainer', 'lorem ipsum', 'tbd', 'todo', 'xx%',
]
NOT_FINAL = ['so far', 'to date', 'this week', 'next week', 'last week', 'in progress', 'work in progress', 'wip',
             'will be updated', 'currently being', 'we are working on', 'still drafting', 'coming soon', 'placeholder']
AI_LEAKS = ['this conversation', 'as an ai', 'in this chat', 'generated by ai', 'ai-generated']  # errors
SOURCE_WORDS = ['transcript', 'transcripts', 'recording', 'meeting notes']  # warnings: cite the session, not the artefact
US = [r'\b\w*(?<!s)iz(e|es|ed|ing|ation|ations)\b', r'\bcolor\w*', r'\bbehavior\w*', r'\bfavor\w*', r'\bcenter(s|ed)?\b',
      r'\bcatalog(s|ed)?\b', r'\bmodeling\b', r'\blabeled\b', r'\bfulfill\b', r'\benrollment\b', r'\bdefense\b',
      r'\banalyz\w*']
UK = [r'\b\w+is(ation|ations)\b', r'\b(organis|prioritis|standardis|optimis|minimis|maximis|recognis|realis|summaris|finalis|categoris|customis|utilis|authoris|operationalis|industrialis|visualis|centralis|normalis)(e|es|ed|ing)\b',
      r'\banalys(e|ed|es|ing)\b', r'\bcolour\w*', r'\bbehaviour\w*', r'\bfavour\w*', r'\bcentre(s|d)?\b', r'\bcatalogue(s|d)?\b',
      r'\bmodelling\b', r'\blabelled\b', r'\btravelled\b', r'\bprogrammes?\b', r'\bdefence\b', r'\benrolment\b', r'\bfulfil\b', r'\bjudgement\b']
US_ALLOW = {'size', 'sizes', 'sized', 'sizing', 'prize', 'seize', 'seized', 'citizen', 'citizens', 'capsize', 'resize', 'resized',
            'oversized', 'downsize', 'downsizing', 'rightsize', 'rightsizing', 'rightsized', 'bitesize', 'outsize', 'outsized'}


class P(HTMLParser):
    """Collect visible text (outside placeholders, scripts and styles), ids, links and resources."""
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack, self.skip, self.text, self.ids, self.hrefs, self.onclick, self.res = [], 0, [], [], [], [], []
        self.tab = None
        self.tabs_nav, self.panels = [], []

    def handle_starttag(self, t, attrs):
        a = dict(attrs)
        cls = (a.get('class') or '').split()
        skip_me = t in ('script', 'style') or 'ph' in cls or 'skel' in cls
        void = t in ('img', 'br', 'hr', 'input', 'meta', 'link', 'source', 'wbr')
        if not void:
            self.stack.append(skip_me)
            if skip_me:
                self.skip += 1
        if a.get('id'):
            self.ids.append(a['id'])
        if t == 'a' and a.get('href'):
            self.hrefs.append(a['href'])
        if a.get('onclick'):
            self.onclick.append(a['onclick'])
        if t == 'img' and a.get('src'):
            self.res.append(('img', a['src']))
        if t == 'script' and a.get('src'):
            self.res.append(('script', a['src']))
        if t == 'link' and a.get('href'):
            self.res.append(('link', a['href']))
        if t == 'button' and 'tab' in cls and a.get('data-tab'):
            self.tabs_nav.append(a['data-tab'])
        if t == 'div' and 'panel' in cls and a.get('data-tab'):
            self.panels.append(a['data-tab'])
            self.tab = a['data-tab']

    def handle_endtag(self, t):
        if t in ('img', 'br', 'hr', 'input', 'meta', 'link', 'source', 'wbr'):
            return
        if self.stack:
            if self.stack.pop():
                self.skip -= 1

    def handle_data(self, d):
        if not self.skip and d.strip():
            self.text.append((self.tab, d))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('html')
    ap.add_argument('--client', help='client name exactly as the client writes it, e.g. "Acme"')
    ap.add_argument('--final', action='store_true', help='treat remaining placeholders as errors')
    ap.add_argument('--internal-names', default='', help='comma-separated delivery-team names to keep out of the content')
    ap.add_argument('--allow-names', default='', help='comma-separated owner names that may appear in the content (e.g. client co-authors)')
    ap.add_argument('--skip-spelling', '--us-ok', dest='skip_spelling', action='store_true', help='skip the spelling check (US English by default, UK if the hub is tagged en-GB)')
    a = ap.parse_args()
    html = open(a.html, encoding='utf-8').read()
    err, warn, info = [], [], []

    p = P()
    p.feed(html)
    text_by_tab = collections.defaultdict(list)
    for tab, d in p.text:
        text_by_tab[tab].append(d)
    full = '\n'.join(d for _, d in p.text)

    # ---- structure
    if set(p.tabs_nav) != set(p.panels):
        err.append(f'Tabs and panels differ: nav={p.tabs_nav} panels={p.panels}')
    dup = [i for i, n in collections.Counter(p.ids).items() if n > 1]
    if dup:
        err.append(f'Duplicate ids: {", ".join(dup[:12])}')
    opens = re.findall(r'SLOT: (\S+)\s*\n\s*Section:', html)
    for k in opens:
        if f'<!-- END SLOT: {k} -->' not in html:
            err.append(f'Slot {k}: END SLOT marker missing (content may have been pasted over it)')
        if not re.search(r'<div class="slot" id="%s"' % re.escape(k), html):
            err.append(f'Slot {k}: slot <div> missing')
    for k in re.findall(r'<!-- END SLOT: (\S+) -->', html):
        if k not in opens:
            err.append(f'END SLOT {k} has no matching SLOT comment')
    # rough tag balance inside each slot
    for k in opens:
        m = re.search(r'<div class="slot" id="%s"[^>]*>' % re.escape(k), html)
        end = html.find(f'<!-- END SLOT: {k} -->')
        if m and end > 0:
            body = re.sub(r'<!--[\s\S]*?-->', '', html[m.end():end])
            for t in ('div', 'table', 'ul', 'ol', 'p', 'figure', 'details'):
                o = len(re.findall(r'<%s[\s>]' % t, body))
                c = len(re.findall(r'</%s>' % t, body))
                adj = 1 if t == 'div' else 0  # the slot's own closing </div>
                if o != c - adj:
                    err.append(f'Slot {k}: unbalanced <{t}> tags ({o} opened, {c - adj} closed)')

    # ---- standard look and feel
    import pathlib, hashlib
    assets = pathlib.Path(__file__).resolve().parent.parent / 'assets'
    css_txt = (assets / 'hub.css').read_text()
    js_txt = (assets / 'hub.js').read_text()
    m = re.search(r'<meta name="generator" content="ahead-deliverable-hub ([^;"]+); look=([0-9a-f]+)(?:; template=([^"]+))?">', html)
    if m and m.group(3):
        print(f'note: built from the {m.group(3).replace("&#x27;", "")} template.')
    if not m:
        err.append('No ahead-deliverable-hub stamp: this file was not built with the skill, so its look may differ. Rebuild it with build.py.')
    else:
        now = hashlib.sha256((css_txt + js_txt).encode()).hexdigest()[:12]
        if m.group(2) != now:
            warn.append(f'Built with skill version {m.group(1)}, whose styles differ from the installed version. The look stays consistent within this file.')
    styles = re.findall(r'<style[^>]*>([\s\S]*?)</style>', html)
    if len(styles) != 1:
        err.append(f'{len(styles)} <style> blocks found; a deliverable hub has exactly one, from the skill. Remove any added styles.')
    elif m and m.group(2) == hashlib.sha256((css_txt + js_txt).encode()).hexdigest()[:12] and not (
            styles[0].endswith(css_txt)
            and re.fullmatch(r"(@font-face\{[^{}]*\}\n)*", styles[0][:len(styles[0]) - len(css_txt)])):
        err.append('The built-in styles have been edited. Restore them by rebuilding, or copy the content into a freshly built hub.')
    if re.search(r'<font\b|\scolor="|\sbgcolor="', html, re.I):
        err.append('Legacy <font> or colour attributes found; use the standard building blocks instead.')
    ok_style = re.compile(r'^(--[a-z]+:[^;]+;?)+$|^background:(rgba\(0,159,220|repeating-linear-gradient)')
    for k in opens:
        mm = re.search(r'<div class="slot" id="%s"[^>]*>' % re.escape(k), html)
        end = html.find(f'<!-- END SLOT: {k} -->')
        if mm and end > 0:
            for st in re.findall(r'\sstyle="([^"]*)"', html[mm.end():end]):
                if not ok_style.match(st.strip()):
                    (err if a.final else warn).append(f'Slot {k}: inline styling "{st[:40]}" changes the standard look; use the building blocks instead.')
                    break

    # ---- self-contained
    for kind, src in p.res:
        if not src.startswith('data:'):
            err.append(f'External {kind} reference (the hub must be self-contained): {src[:90]}')
    ids, tabs = set(p.ids), set(p.panels)
    for h in p.hrefs:
        if h.startswith('#'):
            if h[1:] and h[1:] not in ids and h[1:] not in tabs:
                err.append(f'Broken internal link: {h}')
        elif h.startswith(('http', 'mailto:', 'file:', '//')) or not h.startswith(('#', 'data:', 'javascript:')):
            warn.append(f'Link out of the hub (content should live inside the hub): {h[:90]}')
    for oc in p.onclick:
        for k in re.findall(r"showTab\('([^']+)'\)", oc):
            if k not in tabs:
                err.append(f"showTab('{k}') points to a tab that does not exist")
        for k in re.findall(r"goAnchor\('([^']+)'\)", oc):
            if k not in ids and k not in tabs:
                err.append(f"goAnchor('{k}') points to an id that does not exist")
        for k in re.findall(r"goItem\('([^']+)'\)", oc):
            if 'ri-' + k not in ids:
                err.append(f"Register reference [[{k}]] has no matching register item")

    # ---- placeholders
    ss = slots(html)
    todo = [s for s in ss if not s[4]]
    by_owner = collections.Counter(s[3] for s in todo)
    by_tab = collections.Counter(s[0] for s in todo)
    msg = f'{len(todo)} of {len(ss)} slots still show a placeholder'
    if todo:
        detail = '; '.join(f'{o} {n}' for o, n in by_owner.most_common())
        (err if a.final else info).append(f'{msg}. By owner: {detail}. By tab: ' + ', '.join(f'{t} {n}' for t, n in by_tab.most_common()))
    else:
        info.append(msg)

    # ---- house style (visible content only, placeholders excluded)
    def scan(words, bucket, why):
        for w in words:
            for tab, d in p.text:
                if re.search(r'(?<![\w-])' + re.escape(w) + r'(?![\w-])', d, re.I):
                    bucket.append(f'{why} "{w}" on tab {tab}: ...{snippet(d, w)}...')
                    break

    def snippet(d, w):
        i = d.lower().find(w.lower())
        return re.sub(r'\s+', ' ', d[max(0, i - 50): i + len(w) + 50]).strip()

    for tab, d in p.text:
        if '—' in d:
            err.append(f'Em dash on tab {tab}: ...{snippet(d, chr(0x2014))}... (use a comma, colon or full stop)')
        if '–' in d:
            warn.append(f'En dash on tab {tab}: ...{snippet(d, chr(0x2013))}... (prefer "to" for ranges)')
    scan(BANNED, warn, 'Casual or filler phrase')
    scan(NOT_FINAL, warn, 'Reads as work in progress, but the hub should read as of its final date:')
    scan(AI_LEAKS, err, 'Process or tooling reference that should not appear in client content:')
    scan(SOURCE_WORDS, warn, 'Cite the session or document by name and date instead of')
    lang = (re.search(r'<html lang="([^"]+)"', html) or [None, 'en-US'])[1]
    if not a.skip_spelling:
        seen = set()
        uk = lang.lower().startswith('en-gb')
        for pat in (US if uk else UK):
            for tab, d in p.text:
                for m in re.finditer(pat, d, re.I):
                    w = m.group(0)
                    if w.lower() in US_ALLOW or w.lower() in seen:
                        continue
                    seen.add(w.lower())
                    if uk:
                        warn.append(f'US spelling? "{w}" on tab {tab} (this hub is in UK English: -ise/-isation, colour, behaviour, centre, catalogue, modelling, programme)')
                    else:
                        warn.append(f'UK spelling? "{w}" on tab {tab} (this hub is in US English: -ize/-ization, color, behavior, center, catalog, modeling, program)')
    if a.client:
        for m in re.finditer(r'\b' + re.escape(a.client) + r'\b', full, re.I):
            if m.group(0) != a.client:
                err.append(f'Client name written as "{m.group(0)}"; the client writes it "{a.client}"')
                break
    names = {n.strip() for n in a.internal_names.split(',') if n.strip()}
    names |= {s[3] for s in ss if s[3] and not re.search(r'(lead|architect|consultant|owner|manager|tbc|confirm|engineer)', s[3], re.I)}
    names -= {n.strip() for n in a.allow_names.split(',') if n.strip()}
    for n in sorted(names):
        if re.search(r'\b' + re.escape(n) + r'\b', full):
            err.append(f'Delivery-team name "{n}" appears in the content (keep names out of client-facing text)')

    size = len(html.encode()) / 1024
    info.append(f'File size {size:.0f} KB; {len(p.panels)} tabs; {len(ss)} slots')
    if size > 15000:
        warn.append('File is over 15 MB; compress embedded images (PNG to JPEG or WebP, or smaller dimensions).')

    for title, xs in (('ERRORS', err), ('WARNINGS', warn), ('INFO', info)):
        if xs:
            print(f'\n{title} ({len(xs)})')
            for x in xs:
                print('  -', x)
    print('\nResult:', 'FAIL' if err else 'PASS')
    sys.exit(1 if err else 0)


if __name__ == '__main__':
    main()
